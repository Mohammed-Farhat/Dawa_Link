"""Builds the list of towns and villages a client can name: python -m dawalink.ops.build_areas

Run after `fetch_osm_places`. It reads OpenStreetMap's answer and our hand-written
`data/areas.csv`, and writes `data/areas_osm.csv`: every place the map adds, with its
centre. `prepare_db` loads both files into the `areas` table.

Building again keeps every id: a conversation may point at an area.
"""

import argparse
import csv
import io
import json
import sys
from decimal import Decimal
from pathlib import Path

from dawalink import osm_places
from dawalink.db.reference import AREAS_FILE, OSM_AREAS_FILE, read_areas
from dawalink.domain.geo import Point
from dawalink.osm_places import Listed, Report, Row

COLUMNS = ("id", "area", "district", "other_names", "kind", "ref_lat", "ref_lon", "osm_id")
HEADER = """\
# Towns, villages and neighbourhoods of Lebanon a client can name in chat ("I'm in Zgharta"),
# added to the hand-written areas.csv (docs/04 R-S2, decision log BLD-D15).
#
# Data © OpenStreetMap contributors, available under the Open Database License (ODbL):
# https://www.openstreetmap.org/copyright. Map data as of {as_of}.
#
# GENERATED by `python -m dawalink.ops.build_areas`: do not edit by hand. To correct a
# place, add it to areas.csv (the hand-written row wins) or correct it on the map.
# ids start at 1000 and are never changed or reused. `osm_id` is the map's own number.
"""


def hand_written(path: Path = AREAS_FILE) -> list[Listed]:
    return [
        Listed(
            int(str(area["id"])),
            str(area["name"]),
            str(area["district"]),
            tuple(area["other_names"]),  # type: ignore[arg-type]
            Point(area["ref_lat"], area["ref_lon"]),  # type: ignore[arg-type]
            bool(area["whole_district"]),
        )
        for area in read_areas(path)
    ]


def read_rows(path: Path) -> list[Row]:
    """The generated file as it was built last time; nothing when it isn't there yet."""
    if not path.is_file():
        return []
    with path.open(encoding="utf-8", newline="") as file:
        lines = (line for line in file if not line.startswith("#"))
        return [
            Row(
                int(row["id"]),
                row["area"],
                row["district"],
                tuple(name for name in row["other_names"].split("|") if name),
                row["kind"],
                Point(Decimal(row["ref_lat"]), Decimal(row["ref_lon"])),
                int(row["osm_id"]),
            )
            for row in csv.DictReader(lines)
        ]


def write_rows(path: Path, rows: list[Row], *, as_of: str) -> None:
    with path.open("w", encoding="utf-8", newline="") as file:
        file.write(HEADER.format(as_of=as_of))
        writer = csv.writer(file, lineterminator="\n")
        writer.writerow(COLUMNS)
        for row in rows:
            writer.writerow(
                (
                    row.id,
                    row.name,
                    row.district,
                    "|".join(row.other_names),
                    row.kind,
                    f"{row.point.lat:.5f}",
                    f"{row.point.lon:.5f}",
                    row.osm_id,
                )
            )


def build(answer: Path, hand_file: Path, target: Path) -> tuple[list[Row], Report]:
    if not answer.is_file():
        raise FileNotFoundError(f"No {answer}: run dawalink.ops.fetch_osm_places first.")
    data = json.loads(answer.read_text(encoding="utf-8"))
    listed = hand_written(hand_file)
    found, report = osm_places.read(data["elements"], osm_places.district_names(listed))
    rows, report = osm_places.merge(found, listed, read_rows(target), report)
    as_of = str(data.get("osm3s", {}).get("timestamp_osm_base", ""))[:10]
    write_rows(target, rows, as_of=as_of or "an unknown date")
    return rows, report


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--folder", type=Path, default=Path("data/osm"))
    parser.add_argument("--areas", type=Path, default=AREAS_FILE)
    parser.add_argument("--target", type=Path, default=OSM_AREAS_FILE)
    parser.add_argument("--check", action="store_true", help="list the hand-written centres")
    arguments = parser.parse_args()
    if isinstance(sys.stdout, io.TextIOWrapper):
        # A Windows console can't always print Arabic letters: show "?" rather than stop.
        sys.stdout.reconfigure(errors="replace")
    rows, report = build(arguments.folder / "places.json", arguments.areas, arguments.target)
    print(f"{len(rows)} places written to {arguments.target}")
    for reason, count in sorted(report.left_out.items()):
        print(f"left out, {reason}: {count}")
    for name, district in report.name_twice:
        print(f"  twice in {district}: {name}")
    if arguments.check:
        seen: dict[int, osm_places.Seen] = {}
        for entry in report.seen:  # the biggest place of that name comes first
            seen.setdefault(entry.listed.id, entry)
        for area in hand_written(arguments.areas):
            match = seen.get(area.id)
            where = "not on the map" if match is None else f"{match.km:.2f} km from the map's"
            print(f"  {area.id:>4} {area.name}: {where}")


if __name__ == "__main__":
    main()
