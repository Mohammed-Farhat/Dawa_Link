"""Builds the P-set: python -m dawalink.evals.build_plan_set

50 baskets drawn from a seed, each with its best plans found by trying everything
(`plan_oracle.py`), written to `eval/datasets/plans.jsonl`. The same seed always gives the
same file. `--check` builds it again and compares it with the file, without writing.

The baskets are frozen: the file is built before the planner is run on it, and a basket
is never dropped or redrawn because the planner gets it wrong. A wrong answer is a bug in
the planner, or a mistake in what "best" means that is corrected in the open.

**What a basket is made of:**
- the trips: the road times of the simulated world (`eval/world/travel.json`) from one of
  its client points to some of its pharmacies, and between those pharmacies;
- the medicines: `m1` to `m5`, with invented prices. A box costs its medicine's full price
  less 25%, 40% or 60%, as in the app, so two pharmacies often ask the same price;
- five shapes, ten baskets each, so every situation the planner must handle is there:
  `small`, `split` (a quantity nobody holds alone), `scarce` (not everything can be
  found), `wide` (many pharmacies, some far, and half the time one that holds
  everything) and `ties` (the same price everywhere).
"""

import argparse
import json
import random
import sys
from collections import Counter
from decimal import Decimal
from pathlib import Path

from dawalink.domain.geo import Point, cell
from dawalink.domain.planning import MissingReason
from dawalink.evals import plan_oracle
from dawalink.evals.plan_set import CLIENT, ORDERS, PLANS_FILE, PBox, PCase, PItem
from dawalink.sim import travel_table
from dawalink.sim.travel_table import Table
from dawalink.sim.world import World, load

SEED = 2026
SHAPES = ("small", "split", "scarce", "wide", "ties")
PER_SHAPE = 10
DISCOUNTS = (25, 40, 60)  # the app's three tiers (docs/04 N-4)
REASONS: tuple[MissingReason, ...] = (
    "none_listed",
    "over_budget",
    "expires_too_early",
    "not_on_that_day",
)
HEADER = (
    "// P-set (docs/08 §2.5): baskets with their best plans, found by trying everything. "
    "Generated by `python -m dawalink.evals.build_plan_set`; never edit it by hand.\n"
    "// Medicines and prices are invented. Trips: " + travel_table.CREDIT + "\n"
)


def _cell(lat: float, lon: float) -> str:
    return cell(Point(Decimal(str(lat)), Decimal(str(lon))))


def _name(n: int) -> str:
    return f"ph{n:02d}"


def _pharmacies(
    numbers: random.Random, world: World, table: Table, client: int, shape: str
) -> list[int]:
    """The pharmacies of a basket, as positions in the world's list: mostly near the client."""
    start = world.clients[client - 1]
    car = table[_cell(start.lat, start.lon)]["car"]
    reachable = [n for n, way in enumerate(car) if way is not None]
    nearest = sorted(reachable, key=lambda n: (car[n] or [0])[0])
    count = {
        "small": numbers.randint(2, 4),
        "split": numbers.randint(3, 5),
        "scarce": numbers.randint(3, 6),
        "wide": numbers.randint(9, 14),
        "ties": numbers.randint(3, 6),
    }[shape]
    near = nearest[: count + 2]
    chosen = set(numbers.sample(near, min(count, len(near))))
    if shape == "wide":  # a few from anywhere, so a far but cheap pharmacy can exist
        far = nearest[count + 2 :]
        chosen |= set(numbers.sample(far, min(3, len(far))))
    return sorted(chosen)


def _legs(
    world: World, table: Table, client: int, pharmacies: list[int]
) -> list[tuple[str, str, int, int]] | None:
    """Every trip of the basket, or None if the road table lacks one of them."""
    start = world.clients[client - 1]
    starts = [(CLIENT, _cell(start.lat, start.lon))] + [
        (_name(world.pharmacies[n].n), _cell(world.pharmacies[n].lat, world.pharmacies[n].lon))
        for n in pharmacies
    ]
    legs = []
    for name, origin in starts:
        for n in pharmacies:
            end = _name(world.pharmacies[n].n)
            if end == name:
                continue
            car, walk = table[origin]["car"][n], table[origin]["walk"][n]
            if car is None or walk is None:
                return None
            legs.append((name, end, int(car[0]), int(walk[0])))
    return legs


def _stock(numbers: random.Random, shape: str, names: list[str]) -> tuple[list[PItem], list[PBox]]:
    count = {
        "small": numbers.randint(1, 2),
        "split": numbers.randint(2, 3),
        "scarce": numbers.randint(3, 5),
        "wide": numbers.randint(3, 5),
        "ties": numbers.randint(2, 4),
    }[shape]
    # Half of the wide baskets have one pharmacy that holds everything, somewhere: one
    # stop there, or a shorter trip through two nearer ones.
    has_it_all = numbers.choice(names) if shape == "wide" and numbers.random() < 0.5 else None
    items, boxes = [], []
    for position in range(1, count + 1):
        key = f"m{position}"
        qty = numbers.randint(2, 3) if shape == "split" else numbers.randint(1, 3)
        full_price = numbers.randrange(4, 60) * 50_000
        if shape == "scarce" and numbers.random() < 0.3:
            holders: list[str] = []  # nobody has it
        elif shape == "scarce":
            holders = numbers.sample(names, numbers.randint(1, 2))
        else:
            holders = numbers.sample(names, numbers.randint(1, min(6, len(names))))
        if has_it_all is not None and has_it_all not in holders:
            holders.append(has_it_all)
        one_discount = numbers.choice(DISCOUNTS)
        for holder in sorted(holders):
            batches = 2 if numbers.random() < 0.15 else 1
            for batch in range(batches):
                discount = one_discount if shape == "ties" else numbers.choice(DISCOUNTS)
                available = 1 if shape in ("split", "scarce") else numbers.randint(1, 3)
                if holder == has_it_all:
                    available = 3
                boxes.append(
                    PBox(
                        id=f"{holder}-{key}" + ("-b" if batch else ""),
                        item=key,
                        pharmacy=holder,
                        price_lbp=full_price * (100 - discount) // 100,
                        available=available,
                    )
                )
        reason = numbers.choice(REASONS) if not holders else "none_listed"
        items.append(PItem(key=key, qty=qty, reason_if_none=reason))
    return items, boxes


def _basket(world: World, table: Table, seed: int, number: int, shape: str) -> PCase:
    """Basket `number`: drawn from its own stream, so one basket never changes another."""
    attempt = 0
    while True:
        numbers = random.Random(f"{seed}:{number}:{attempt}")
        attempt += 1
        client = numbers.randint(1, len(world.clients))
        pharmacies = _pharmacies(numbers, world, table, client, shape)
        legs = _legs(world, table, client, pharmacies)
        if legs is None:
            continue  # a place with no road: draw the places again
        names = [_name(world.pharmacies[n].n) for n in pharmacies]
        items, boxes = _stock(numbers, shape, names)
        if not boxes:
            continue  # nothing on any shelf: there is no plan to check
        case = PCase(
            id=f"P-{number:04d}",
            shape=shape,
            client=client,
            items=items,
            boxes=boxes,
            legs=legs,
            expected={},
        )
        expected = {order: plan_oracle.best_plans(case, order) for order in ORDERS}
        return case.model_copy(update={"expected": expected})


def build(world: World, table: Table, seed: int = SEED) -> list[PCase]:
    shapes = [shape for shape in SHAPES for _ in range(PER_SHAPE)]
    return [_basket(world, table, seed, n, shape) for n, shape in enumerate(shapes, start=1)]


def text_of(cases: list[PCase]) -> str:
    lines = [json.dumps(case.model_dump(mode="json"), separators=(",", ":")) for case in cases]
    return HEADER + "\n".join(lines) + "\n"


def what_is_in_it(cases: list[PCase]) -> dict[str, int]:
    """Counts for the data sheet: is every situation the planner must handle in the set?"""
    counts: Counter[str] = Counter()
    for case in cases:
        best = case.expected["nearest"][0]
        wanted = sum(item.qty for item in case.items)
        counts["baskets"] += 1
        counts["best plan has 2 stops or more"] += best.stops > 1
        counts["not everything can be found"] += best.units < wanted
        held: Counter[tuple[str, str]] = Counter()
        for box in case.boxes:
            held[(box.item, box.pharmacy)] += box.available
        counts["a quantity must be split across pharmacies"] += any(
            item.qty > max((n for (key, _), n in held.items() if key == item.key), default=item.qty)
            for item in case.items
        )
        prices = Counter((box.item, box.price_lbp) for box in case.boxes)
        counts["two pharmacies ask the same price"] += any(n > 1 for n in prices.values())
        counts["more than 8 pharmacies"] += len({box.pharmacy for box in case.boxes}) > 8
        for order in ORDERS[1:]:
            other = case.expected[order][0]
            counts[f"{order} changes the first plan"] += set(other.pharmacies) != set(
                best.pharmacies
            )
        counts["fewer than 3 plans exist"] += len(case.expected["nearest"]) < 3
        counts["a detour looks shorter in the road table"] += (
            plan_oracle.shorter_with_a_detour(case) > 0
        )
    return dict(counts)


def main() -> None:
    parser = argparse.ArgumentParser(description=(__doc__ or "").split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="compare with the file; write nothing")
    parser.add_argument("--out", type=Path, default=PLANS_FILE)
    args = parser.parse_args()

    table = travel_table.read()
    if table is None:
        sys.exit("The road table (eval/world/travel.json) is missing.")
    cases = build(load(), table)
    text = text_of(cases)
    for what, count in what_is_in_it(cases).items():
        print(f"{count:3d}  {what}")
    if args.check:
        same = args.out.exists() and args.out.read_text(encoding="utf-8") == text
        print(
            "the file is what the seed gives"
            if same
            else "THE FILE DIFFERS from what the seed gives"
        )
        sys.exit(0 if same else 1)
    args.out.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
